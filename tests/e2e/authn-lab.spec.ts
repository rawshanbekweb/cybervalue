test.describe("an Intermediate student", () => {
  test.skip(!process.env.DATABASE_URL, "Requires DATABASE_URL");
  const id = randomUUID();
  const code = newCode();

  test.beforeAll(async () => {
    const client = new Client({ connectionString: process.env.DATABASE_URL });
    await client.connect();
    await client.query(
      `INSERT INTO "Student" (id, name, level, "codeHash", "updatedAt")
       VALUES ($1, 'Signin Pupil', 'intermediate', $2, now())`,
      [id, createHash("sha256").update(code).digest("hex")],
    );
    await client.end();
  });

  test.afterAll(async () => {
    const client = new Client({ connectionString: process.env.DATABASE_URL });
    await client.connect();
    await client.query(`DELETE FROM "Student" WHERE id = $1`, [id]);
    await client.end();
  });

  test("apply the password policy", async ({ page }) => {
    await page.emulateMedia({ reducedMotion: "reduce" });
    await page.goto("/student/login");
    await page.getByLabel("Access code").fill(code);
    await page.getByRole("button", { name: "Enter" }).click();
    await expect(page).toHaveURL(/\/student$/);

    await page.goto("/intermediate/authn#lesson/3");
    const accept = [false, true, false, false, true, false];
    const items = page.locator(".sc-line");
    await expect(items).toHaveCount(6);
    await items.nth(0).getByLabel("Accept").check();
    await expect(page.locator(".sd-bad")).toHaveCount(1);
    for (let i = 0; i < accept.length; i++)
      await items
        .nth(i)
        .getByLabel(accept[i] ? "Accept" : "Reject")
        .check();
    await expect(items.nth(0)).toContainText("On the breached list");
    await expect(items.nth(3)).toContainText("Contains the username");
    await expect(page.locator(".nl-card .nl-pass")).toContainText(
      "Only the two long phrases pass",
    );
    await pass(page);
    await audit(page, "policy");
  });
});

