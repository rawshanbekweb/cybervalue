test.describe("an Intermediate student", () => {
  test.skip(!process.env.DATABASE_URL, "Requires DATABASE_URL");
  const id = randomUUID();
  const code = newCode();

  test.beforeAll(async () => {
    const client = new Client({ connectionString: process.env.DATABASE_URL });
    await client.connect();
    await client.query(
      `INSERT INTO "Student" (id, name, level, "codeHash", "updatedAt")
       VALUES ($1, 'Analyst Pupil', 'intermediate', $2, now())`,
      [id, createHash("sha256").update(code).digest("hex")],
    );
    await client.end();
  });

  test.afterAll(async () => {
    const client = new Client({ connectionString: process.env.DATABASE_URL });
    await client.connect();
    await client.query(`DELETE FROM "Student" WHERE id = $1`, [id]);
    await client.end();
  });

  test("mark the boundaries and sort the threats", async ({ page }) => {
    await page.emulateMedia({ reducedMotion: "reduce" });
    await page.goto("/student/login");
    await page.getByLabel("Access code").fill(code);
    await page.getByRole("button", { name: "Enter" }).click();
    await expect(page).toHaveURL(/\/student$/);

    await page.goto("/intermediate/stride#lesson/3");
    for (const n of ["1.", "2.", "3.", "6."])
      await page.getByLabel(new RegExp(`^${n.replace(".", "\\.")} `)).check();
    await expect(page.locator(".nl-card .nl-pass")).toContainText("Four flows");
    await pass(page);
    await audit(page, "boundary");

    await page.goto("/intermediate/stride#lesson/5");
    const letters = ["S", "T", "R", "I", "D", "E"];
    const selects = page.locator(".sd-threat select");
    await expect(selects).toHaveCount(6);
    await selects.nth(0).selectOption("T");
    await expect(page.locator(".sd-bad")).toHaveCount(1);
    for (let i = 0; i < letters.length; i++)
      await selects.nth(i).selectOption(letters[i]);
    await expect(page.locator(".nl-card .nl-pass")).toContainText(
      "one threat for every letter",
    );
    await pass(page);
    await audit(page, "stride");
  });
});

