test.describe("an Intermediate student", () => {
  test.skip(!process.env.DATABASE_URL, "Requires DATABASE_URL");
  const id = randomUUID();
  const code = newCode();

  test.beforeAll(async () => {
    const client = new Client({ connectionString: process.env.DATABASE_URL });
    await client.connect();
    await client.query(
      `INSERT INTO "Student" (id, name, level, "codeHash", "updatedAt")
       VALUES ($1, 'Stego Pupil', 'intermediate', $2, now())`,
      [id, createHash("sha256").update(code).digest("hex")],
    );
    await client.end();
  });

  test.afterAll(async () => {
    const client = new Client({ connectionString: process.env.DATABASE_URL });
    await client.connect();
    await client.query(`DELETE FROM "Student" WHERE id = $1`, [id]);
    await client.end();
  });

  test("an acrostic and a zero-width secret", async ({ page }) => {
    await page.emulateMedia({ reducedMotion: "reduce" });
    await page.goto("/student/login");
    await page.getByLabel("Access code").fill(code);
    await page.getByRole("button", { name: "Enter" }).click();
    await expect(page).toHaveURL(/\/student$/);

    await page.goto("/intermediate/stego#lesson/2");
    await page.getByLabel("The hidden word").fill("meet now");
    await expect(page.locator(".nl-card .nl-pass")).toContainText("MEETNOW");
    await pass(page);
    await audit(page, "acrostic");

    await page.goto("/intermediate/stego#lesson/3");
    await expect(page.locator(".cb-label").first()).toContainText(
      "actual length",
    );
    await page
      .getByRole("button", { name: "Show invisible characters" })
      .click();
    await expect(page.locator(".sg-bit")).toHaveCount(40);
    await page.getByRole("button", { name: /Decode the bits/ }).click();
    await expect(page.locator(".sg-bits")).toContainText("00110001 → 1");
    await page.getByLabel("The hidden text").fill("13:00");
    await pass(page);
    await audit(page, "zerowidth");
  });
});

